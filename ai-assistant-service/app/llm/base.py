from abc import ABC, abstractmethod
from collections.abc import AsyncGenerator
from typing import Any, Literal

from pydantic import BaseModel, Field


class ImageAttachment(BaseModel):
    """Multimodal image payload for damaged product inspection (Scenario D.1)."""

    media_type: str = Field(default="image/jpeg", description="MIME type such as image/jpeg or image/png")
    base64_data: str | None = Field(default=None, description="Base64-encoded image bytes")
    url: str | None = Field(default=None, description="Public or internal URL of the image")


class ToolCallRequest(BaseModel):
    """Represents a function/tool invocation requested by the LLM."""

    id: str = Field(default="", description="Unique tool call identifier generated by the provider")
    tool_name: str = Field(..., description="Name of the registered tool to execute")
    arguments: dict[str, Any] = Field(default_factory=dict, description="Parsed JSON arguments for the tool")


class ToolDefinition(BaseModel):
    """Provider-agnostic tool schema definition."""

    name: str
    description: str
    parameters: dict[str, Any] = Field(
        default_factory=lambda: {"type": "object", "properties": {}, "required": []}
    )


class ChatMessage(BaseModel):
    """Unified conversation message model across all LLM providers."""

    role: Literal["system", "user", "assistant", "tool"]
    content: str = ""
    tool_calls: list[ToolCallRequest] = Field(default_factory=list)
    tool_call_id: str | None = None
    tool_name: str | None = None
    images: list[ImageAttachment] = Field(default_factory=list)


class AgentResponse(BaseModel):
    """Unified response contract returned by any LLM provider."""

    content: str = ""
    tool_calls: list[ToolCallRequest] = Field(default_factory=list)
    finish_reason: str = "stop"
    provider_used: str
    model_used: str


class BaseLLMProvider(ABC):
    """Abstract strategy contract that all LLM providers (Claude, OpenAI, Gemini, Local) must implement."""

    provider_name: str
    model_name: str

    @abstractmethod
    async def chat(
        self,
        messages: list[ChatMessage],
        tools: list[ToolDefinition] | None = None,
        temperature: float = 0.2,
    ) -> AgentResponse:
        """Executes a single turn of chat completion with optional tool-calling definitions."""

    @abstractmethod
    async def stream_chat(
        self,
        messages: list[ChatMessage],
        tools: list[ToolDefinition] | None = None,
        temperature: float = 0.2,
    ) -> AsyncGenerator[str, None]:
        """Streams response tokens for Server-Sent Events (SSE) typewriter effect."""
        yield ""  # pragma: no cover
