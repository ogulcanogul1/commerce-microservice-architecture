from abc import ABC, abstractmethod
from typing import Any, Literal
from pydantic import BaseModel, Field


class ToolDefinition(BaseModel):
    """Defines an agentic tool/function schema that the LLM is permitted to invoke."""

    name: str = Field(
        description="Unique identifier and function name of the tool (e.g. 'get_customer_orders')"
    )
    description: str = Field(
        description="Detailed explanation of what the tool does and when the LLM should invoke it"
    )
    parameters: dict[str, Any] = Field(
        description="JSON Schema specifying the expected input parameters, types, and required fields"
    )


class ToolCallRequest(BaseModel):
    """Captured function invocation request initiated by the LLM."""

    call_id: str = Field(
        description="Unique execution ID generated by the provider for this tool call"
    )
    tool_name: str = Field(
        description="Name of the function the LLM decided to invoke"
    )
    arguments: dict[str, Any] = Field(
        default_factory=dict,
        description="Dictionary of validated arguments parsed from the model's function call"
    )


class ChatMessage(BaseModel):
    """Represents a single chat turn in the conversation history."""

    role: Literal["system", "user", "assistant", "tool"] = Field(
        description="Role of the message sender: system (instructions), user, assistant (LLM), or tool (function execution output)"
    )
    content: str = Field(
        description="Text content of the message"
    )
    tool_call_id: str | None = Field(
        default=None,
        description="Identifier of the specific tool call if this message is a response from a tool"
    )
    tool_calls: list[ToolCallRequest] | None = Field(
        default=None,
        description="List of tool invocations requested by the assistant in this turn"
    )
    name: str | None = Field(
        default=None,
        description="Name of the tool that produced this result (required by some providers like Gemini)"
    )


class TokenUsage(BaseModel):
    """Token consumption statistics for an LLM interaction."""

    input_tokens: int | None = Field(
        default=None,
        description="Number of prompt/context tokens sent to the model"
    )
    output_tokens: int | None = Field(
        default=None,
        description="Number of completion/candidate tokens generated by the model"
    )


class LLMResponse(BaseModel):
    """Normalized response envelope returned by any LLM provider implementation."""

    content: str = Field(
        default="",
        description="Direct textual answer generated by the LLM for the user"
    )
    tool_calls: list[ToolCallRequest] = Field(
        default_factory=list,
        description="List of tool invocations requested by the model before producing a final answer"
    )
    provider: str = Field(
        description="Name of the LLM provider handling the turn (e.g. 'gemini', 'openai', 'claude', 'local')"
    )
    model: str = Field(
        description="Exact model identifier utilized (e.g. 'gemini-2.5-flash', 'gpt-4o', 'llama-3.2')"
    )
    usage: TokenUsage | None = Field(
        default=None,
        description="Token consumption statistics if reported by the provider"
    )


class BaseLLMProvider(ABC):
    """
    Abstract Base Class that every LLM provider (OpenAI, Gemini, Claude, Local/Ollama)
    must implement to ensure a unified contract.
    """

    provider: str = ""

    def __init__(self, model_name: str, api_key: str = "", base_url: str = "") -> None:
        self.model_name = model_name
        self.api_key = api_key
        self.base_url = base_url
        if not getattr(self, "provider", ""):
            self.provider = self.__class__.__name__.lower().replace("provider", "")

    @abstractmethod
    async def generate(
        self,
        messages: list[ChatMessage],
        tools: list[ToolDefinition] | None = None,
        temperature: float = 0.7,
        max_tokens: int | None = None,
    ) -> LLMResponse:
        """
        Execute an asynchronous chat completion request against the LLM provider.

        Args:
            messages: List of chronological conversation messages.
            tools: Optional catalog of agentic tools available for function calling.
            temperature: Sampling temperature (0.0 to 1.0).
            max_tokens: Maximum number of tokens to generate in the response.

        Returns:
            Normalized LLMResponse containing the text output or required tool calls.
        """
        pass
