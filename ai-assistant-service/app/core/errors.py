"""RFC 7807 Problem Details Standard Error Model and Exception Hierarchy.

AGENTS.md Kural 7: İstisna Sınıflandırma Standardı (Retryable vs NonRetryable).
Mikroservis mimarisinde istemcilerin ve API Gateway'in hatalara doğru tepki verebilmesi için:
- 4xx ve iş kuralı ihlalleri NonRetryable (asla tekrar denenmez)
- 503 Overloaded, 429 Rate Limit/Budget gibi geçici durumlar Retryable (tekrar denenebilir)
olarak açıkça sınıflandırılır.
"""

from __future__ import annotations

from enum import StrEnum
import http
import logging
from typing import Any

from fastapi import FastAPI, Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field
from starlette.exceptions import HTTPException as StarletteHTTPException

logger = logging.getLogger(__name__)


class ProblemType(StrEnum):
    """RFC 7807 standardında hatanın tipini ve dokümantasyonunu belirten URI tanımları.
    
    Neden URL formatında?
    Frontend veya API Gateway, hata mesajındaki serbest metni (detail) okuyup parse etmeye çalışmaz.
    Onun yerine makine tarafından okunabilen bu benzersiz URI'ye bakar.
    Örn: if (error.type === '.../ai-overloaded') -> kullanıcıya 'AI meşgul' uyarısı göster.
    
    - BLANK: Standart HTTP durum kodları için varsayılan RFC 7807 URI'si ('about:blank').
    - AI_OVERLOADED: Eşzamanlı LLM istek kapasitesi dolduğunda (503).
    - TOKEN_BUDGET_EXCEEDED: Kullanıcının günlük veya dakikalık token kotası bittiğinde (429).
    - BUDGET_UNAVAILABLE: Redis veya bütçe veritabanı çöktüğünde fail-closed modunda (503).
    """

    BLANK = "about:blank"
    AI_OVERLOADED = "https://api.commerce.com/errors/ai-overloaded"
    TOKEN_BUDGET_EXCEEDED = "https://api.commerce.com/errors/token-budget-exceeded"
    BUDGET_UNAVAILABLE = "https://api.commerce.com/errors/budget-unavailable"


class ProblemDetails(BaseModel):
    """RFC 7807 Problem Details standart veri modeli (application/problem+json).
    
    Bu model istemciye dönen JSON gövdesinin şemasını belirler.
    """

    # Hatanın türünü belirten makine-okunabilir URI (Örn: 'https://api.commerce.com/errors/ai-overloaded')
    type: str = Field(
        default=ProblemType.BLANK.value,
        description="A URI reference that identifies the problem type",
    )

    # İnsanların okuyabileceği kısa başlık (Örn: 'Service Unavailable' veya 'Service Overloaded')
    title: str = Field(
        description="A short, human-readable summary of the problem type",
    )

    # HTTP durum kodu (Örn: 429, 503, 404, 422). JSON çıktısında sayı olarak serileştirilir.
    status: int = Field(
        description="The HTTP status code generated by the origin server for this occurrence",
    )

    # Bu spesifik hata olayına dair açıklayıcı mesaj
    detail: str = Field(
        description="A human-readable explanation specific to this occurrence of the problem",
    )

    # Hatanın oluştuğu HTTP istek yolu (Örn: '/api/v1/chat')
    instance: str | None = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence of the problem",
    )

    # 422 Doğrulama hatalarında hangi parametrelerin hatalı olduğunu gösteren liste
    errors: list[dict[str, Any]] | None = Field(
        default=None,
        description="Detailed list of validation errors (for 422 Unprocessable Entity)",
    )

    # İstemcinin bu isteği tekrar deneyip deneyemeyeceğini belirten bayrak (True: Geçici, False: Kalıcı)
    retryable: bool | None = Field(
        default=None,
        description="Indicates whether the client can retry the request later",
    )

    # retryable True olduğunda istemcinin kaç saniye beklemesi gerektiği (HTTP Retry-After ile eşleşir)
    retry_after_seconds: int | None = Field(
        default=None,
        ge=1,
        description="Suggested number of seconds to wait before retrying",
    )


# ---------------------------------------------------------------------------
# Exception Hierarchy (İstisna Sınıflandırma Hiyerarşisi)
# ---------------------------------------------------------------------------

class BaseProblemException(StarletteHTTPException):
    """Tüm uygulama içi RFC 7807 problem istisnalarının temel sınıfı.
    
    StarletteHTTPException'dan miras alır; böylece FastAPI bu istisnayı doğrudan bir HTTP hatası olarak tanır.
    """

    def __init__(
        self,
        status_code: int,
        detail: str,
        *,
        problem_type: str | ProblemType = ProblemType.BLANK,
        title: str | None = None,
        headers: dict[str, str] | None = None,
    ) -> None:
        # Eğer problem_type bir StrEnum nesnesiyse string değerini al (Örn: ProblemType.AI_OVERLOADED -> "https://...")
        type_str = problem_type.value if isinstance(problem_type, ProblemType) else problem_type

        # Üst sınıf olan StarletteHTTPException'ı başlat (status_code, detail ve HTTP header'larını kaydeder)
        super().__init__(status_code=status_code, detail=detail, headers=headers)

        # RFC 7807'ye özgü ek alanları sınıf üzerinde sakla
        self.problem_type = type_str
        self.custom_title = title


# Geriye uyumluluk için takma ad (alias)
ProblemHTTPException = BaseProblemException


class NonRetryableException(BaseProblemException):
    """Kalıcı veya iş kuralı ihlali kaynaklı hatalar (Örn: 4xx, 422, 404).
    
    İstemci aynı isteği parametrelerini değiştirmeden tekrar gönderirse yine aynı hatayı alır.
    Bu sınıfta 'retry_after_seconds' parametresi hiç tanımlanmamıştır; böylece mantıksal çelişki engellenir.
    """

    retryable: bool = False


class RetryableException(BaseProblemException):
    """Geçici altyapı veya aşırı yük kaynaklı hatalar (Örn: 503 Overload, 429 Rate Limit/Token Kotası).
    
    İstemci belirtilen bekleme süresi ('retry_after_seconds') sonunda isteği tekrar deneyebilir.
    """

    retryable: bool = True

    def __init__(
        self,
        status_code: int,
        detail: str,
        *,
        problem_type: str | ProblemType = ProblemType.BLANK,
        title: str | None = None,
        retry_after_seconds: int | None = None,
        headers: dict[str, str] | None = None,
    ) -> None:
        # Mevcut HTTP başlıklarını kopyala (yoksa boş bir sözlük oluştur)
        merged_headers = dict(headers or {})

        # Eğer bir tekrar deneme bekleme süresi belirtilmişse, HTTP standartlarındaki 'Retry-After' başlığını ekle
        # Bu başlık API Gateway ve HTTP istemcilerinin ne kadar süre bekleyeceğini anlamasını sağlar.
        if retry_after_seconds is not None:
            merged_headers["Retry-After"] = str(retry_after_seconds)

        # Üst sınıf olan BaseProblemException'ı güncellenmiş başlıklarla başlat
        super().__init__(
            status_code=status_code,
            detail=detail,
            problem_type=problem_type,
            title=title,
            headers=merged_headers,
        )

        # Bekleme süresini sınıf üzerinde de sakla (ProblemDetails modeline aktarılabilmesi için)
        self.retry_after_seconds = retry_after_seconds


# ---------------------------------------------------------------------------
# Global Exception Handlers (FastAPI Hata Yakalayıcıları)
# ---------------------------------------------------------------------------

def register_problem_details_handlers(app: FastAPI) -> None:
    """FastAPI uygulamasına RFC 7807 uyumlu global hata yakalayıcılarını kaydeder."""

    @app.exception_handler(StarletteHTTPException)
    async def http_exception_handler(request: Request, exc: StarletteHTTPException) -> JSONResponse:
        """FastAPI veya Starlette tarafından fırlatılan tüm HTTPException'ları yakalar."""

        # 1. Adım: HTTP durum kodunun standart metin karşılığını bul (Örn: 404 -> 'Not Found', 503 -> 'Service Unavailable')
        try:
            status_obj = http.HTTPStatus(exc.status_code)
            title = status_obj.phrase
        except ValueError:
            # Standart dışı bilinmeyen bir kod geldiyse genel bir başlık ver
            title = "HTTP Error"

        # 2. Adım: Varsayılan RFC 7807 alanlarını hazırla
        problem_type = ProblemType.BLANK.value
        retryable: bool | None = None
        retry_after_seconds: int | None = None

        # 3. Adım: Fırlatılan hata bizim kendi tanımladığımız BaseProblemException sınıfından mı türemiş?
        if isinstance(exc, BaseProblemException):
            # Eğer geliştirici özel bir başlık belirttiyse onu kullan (Örn: 'Service Overloaded')
            if exc.custom_title:
                title = exc.custom_title

            # Hata tipini al (Örn: 'https://api.commerce.com/errors/ai-overloaded')
            problem_type = exc.problem_type

            # Hataya göre retryable semantiğini belirle
            if isinstance(exc, RetryableException):
                retryable = True
                retry_after_seconds = exc.retry_after_seconds
            elif isinstance(exc, NonRetryableException):
                retryable = False

        # 4. Adım: RFC 7807 standart Pydantic veri modelini oluştur
        problem = ProblemDetails(
            type=problem_type,
            title=title,
            status=exc.status_code,
            detail=str(exc.detail),
            instance=request.url.path,  # İsteğin geldiği endpoint yolu (örn: /api/v1/chat)
            retryable=retryable,
            retry_after_seconds=retry_after_seconds,
        )

        # 5. Adım: İstisna üzerinde varsa HTTP başlıklarını al (Örn: Retry-After başlığı)
        headers = getattr(exc, "headers", None)

        # 6. Adım: Standart 'application/problem+json' içerik türüyle (media_type) JSON yanıtı dön
        return JSONResponse(
            status_code=exc.status_code,
            content=problem.model_dump(exclude_none=True),  # None olan alanları JSON çıktısına dahil etme
            headers=headers,
            media_type="application/problem+json",
        )

    @app.exception_handler(RequestValidationError)
    async def validation_exception_handler(
        request: Request, exc: RequestValidationError
    ) -> JSONResponse:
        """Pydantic istek doğrulama (validation) hatalarını (422) yakalar."""

        # 1. Adım: Pydantic'in ürettiği karmaşık hata yapısını istemcinin kolay okuyabileceği sade bir listeye dönüştür
        errors = []
        for err in exc.errors():
            # Hatalı alanın adını bul (Örn: 'body -> message')
            loc = " -> ".join(str(l) for l in err.get("loc", []))
            errors.append({
                "field": loc,
                "message": err.get("msg", ""),
                "type": err.get("type", ""),
            })

        # 2. Adım: 422 hatası doğası gereği kalıcıdır (girdi düzeltilmeden tekrar denense de başarısız olur)
        problem = ProblemDetails(
            type=ProblemType.BLANK.value,
            title="Unprocessable Entity",
            status=422,
            detail="İstek parametreleri veya gövdesi doğrulanamadı.",
            instance=request.url.path,
            errors=errors,
            retryable=False,  # Doğrulama hataları asla retry edilmez (NonRetryable)
        )

        # 3. Adım: 422 JSON çıktısını dön
        return JSONResponse(
            status_code=422,
            content=problem.model_dump(exclude_none=True),
            media_type="application/problem+json",
        )

    @app.exception_handler(Exception)
    async def unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
        """Kodda try/except ile yakalanmamış tüm beklenmeyen sunucu hatalarını (500) yakalar."""

        # 1. Adım: Hatayı sunucu loglarına tüm stack trace'iyle kaydet (geliştirici terminalde görebilsin)
        logger.exception("Beklenmeyen sunucu hatası (500): %s", exc)

        # 2. Adım: GÜVENLİK KURALI -> İstemciye asla Python hata detayını, SQL hatasını veya kod satırını sızdırma!
        # Dışarıya yalnızca genel, kurumsal ve güvenli bir mesaj dönülür.
        problem = ProblemDetails(
            type=ProblemType.BLANK.value,
            title="Internal Server Error",
            status=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Sunucu tarafında beklenmeyen bir hata oluştu.",
            instance=request.url.path,
            retryable=True,  # 500 hataları genelde geçici servis/bağlantı hatası olabileceğinden retryable kabul edilir
        )

        # 3. Adım: 500 JSON çıktısını dön
        return JSONResponse(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            content=problem.model_dump(exclude_none=True),
            media_type="application/problem+json",
        )
